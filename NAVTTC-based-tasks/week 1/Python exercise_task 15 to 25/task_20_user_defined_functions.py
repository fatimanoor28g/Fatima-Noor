
# Task 20: User-Defined Functions

# Function without parameters
def greet():
    print("Hello, Python!")

greet()

# Function with parameters
def add(a, b):
    return a + b

result = add(10, 20)
print("Sum =", result)

# Function to find square
def square(n):
    return n * n

print("Square =", square(5))
