
# Task 22: Tuple

colors = ("Red", "Green", "Blue")

# Display tuple and access elements
print("Tuple:", colors)
print("First color:", colors[0])
print("Tuple length:", len(colors))

# Loop through tuple
for color in colors:
    print(color)

# Count and index
numbers = (1, 2, 2, 3, 2)
print("Count of 2:", numbers.count(2))
print("Index of 3:", numbers.index(3))
